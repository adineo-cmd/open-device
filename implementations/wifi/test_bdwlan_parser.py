class TestFixtureDeterminism(unittest.TestCase):
    """Fixtures must regenerate byte-identically."""

    def test_regeneration_is_byte_exact(self):
        before = {}
        for name in sorted(os.listdir(FIX)):
            with open(os.path.join(FIX, name), "rb") as handle:
                before[name] = handle.read()
        make_fixture.write_all()
        after = {}
        for name in sorted(os.listdir(FIX)):
            with open(os.path.join(FIX, name), "rb") as handle:
                after[name] = handle.read()
        self.assertEqual(before, after)

    def test_all_expected_fixtures_exist(self):
        expected = {
            "board2_ath11k.bin",
            "board2_ath11k_elf.bin",
            "board2_ath10k.bin",
            "board2_bad_checksum.bin",
            "body_sentinel.bin",
            "body_overrun.bin",
            "no_magic.bin",
            "truncated.bin",
        }
        present = set(os.listdir(FIX))
        self.assertTrue(expected.issubset(present), expected - present)


