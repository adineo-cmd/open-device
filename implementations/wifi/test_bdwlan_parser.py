"""test_bdwlan_parser.py — unittest suite for the clean-room wifi parser.

======================================================================
CLEAN-ROOM STATEMENT
Written from the Linux kernel ath10k/ath11k board-data walk (GPL-2.0, read
2026-11-28), ddimension/ath11k-board-bin-tool FORMAT.md (read 2026-11-28),
and this repository's research/fleet/bdwlan-format.md and
research/fleet/wifi-wpss.md. No proprietary payload is read or committed.

The fixtures are synthetic and deterministic and are generated by
make_fixture.py at import time, because every fixture extension they use
(.bin) is gitignored. Tests that need a real payload skip unless
BDWLAN_FIXTURE_REAL names a directory holding board-2.bin files.
======================================================================

The suite covers the four traps this parser exists to avoid:

  * the (0,0) sentinel that makes a naive walk report phantom tags
  * the ELF32 e_phnum index, which is 10 and not 9
  * the ALIGN(len, 4) skip at both the container and the tag level
  * the 0x0a checksum, which must not include itself
"""

import os
import struct
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bdwlan_parser as bp
import make_fixture

FIX = os.path.join(HERE, "fixtures")
REAL = os.environ.get("BDWLAN_FIXTURE_REAL")


def setUpModule():
    """Regenerate fixtures before the suite runs.

    The fixtures are synthetic and deterministic, and their extension is
    gitignored, so they are generated here rather than committed. Nothing
    device-derived is written: see make_fixture.py.
    """
    make_fixture.write_all()


def load(name):
    """Read one fixture and return its bytes."""
    with open(os.path.join(FIX, name), "rb") as handle:
        return handle.read()


class TestAlignAndMagic(unittest.TestCase):
    """The two pure helpers every other layer depends on."""

    def test_align4_rounds_up(self):
        self.assertEqual(bp.align4(0), 0)
        self.assertEqual(bp.align4(1), 4)
        self.assertEqual(bp.align4(4), 4)
        self.assertEqual(bp.align4(5), 8)
        self.assertEqual(bp.align4(19), 20)

    def test_magic_field_is_20_for_both_magics(self):
        self.assertEqual(bp.magic_field_size(bp.ATH11K_MAGIC), 20)
        self.assertEqual(bp.magic_field_size(bp.ATH10K_MAGIC), 20)

    def test_magic_field_is_strlen_plus_nul_aligned(self):
        for magic in bp.MAGICS:
            self.assertEqual(bp.magic_field_size(magic), bp.align4(len(magic) + 1))

    def test_sniff_finds_each_magic(self):
        self.assertEqual(bp.sniff(bp.ATH11K_MAGIC + bytes(8)), bp.ATH11K_MAGIC)
        self.assertEqual(bp.sniff(bp.ATH10K_MAGIC + bytes(8)), bp.ATH10K_MAGIC)

    def test_sniff_rejects_unknown(self):
        self.assertIsNone(bp.sniff(b"QCA-ATH12K-BOARD" + bytes(8)))
        self.assertIsNone(bp.sniff(b""))


class TestChecksum(unittest.TestCase):
    """The 0x0a XOR law and its self-exclusion property."""

    def test_checksum_of_zero_body_is_all_ones(self):
        self.assertEqual(bp.xor_checksum(bytes(64)), 0xFFFF)

    def test_checksum_ignores_the_stored_word(self):
        body = bytearray(64)
        body[0x0A:0x0C] = struct.pack("<H", 0xBEEF)
        first = bp.xor_checksum(bytes(body))
        body[0x0A:0x0C] = struct.pack("<H", 0x1234)
        self.assertEqual(first, bp.xor_checksum(bytes(body)))

    def test_checksum_changes_when_covered_byte_changes(self):
        body = bytearray(64)
        first = bp.xor_checksum(bytes(body))
        body[0x20] ^= 0x01
        self.assertNotEqual(first, bp.xor_checksum(bytes(body)))

    def test_stored_checksum_none_when_short(self):
        self.assertIsNone(bp.stored_checksum(bytes(4)))

    def test_fixture_checksums_verify(self):
        result = bp.parse(load("board2_ath11k.bin"))
        for entry in result["board_entries"]:
            self.assertTrue(entry["checksum_ok"], entry["name"])

    def test_deliberately_bad_checksum_is_reported(self):
        result = bp.parse(load("board2_bad_checksum.bin"))
        self.assertFalse(result["board_entries"][0]["checksum_ok"])

    def test_bad_checksum_off_by_three(self):
        data = load("board2_bad_checksum.bin")
        result = bp.parse(data)
        entry = result["board_entries"][0]
        self.assertFalse(entry["checksum_ok"])


class TestContainerWalk(unittest.TestCase):
    """Top-level magic plus {le32 id, le32 len} chain."""

    def test_walk_finds_two_boards_and_one_regdb(self):
        magic, field, elements = bp.walk_container(load("board2_ath11k.bin"))
        self.assertEqual(magic, bp.ATH11K_MAGIC)
        self.assertEqual(field, 20)
        self.assertEqual(len(elements), 3)
        self.assertEqual([e[0] for e in elements], [0, 0, 1])

    def test_ath10k_magic_container_walks(self):
        magic, _field, elements = bp.walk_container(load("board2_ath10k.bin"))
        self.assertEqual(magic, bp.ATH10K_MAGIC)
        self.assertEqual(len(elements), 1)

    def test_walk_raises_without_magic(self):
        with self.assertRaises(ValueError):
            bp.walk_container(load("no_magic.bin"))

    def test_walk_raises_on_truncated_element(self):
        with self.assertRaises(ValueError):
            bp.walk_container(load("truncated.bin"))

    def test_walk_raises_on_short_buffer(self):
        with self.assertRaises(ValueError):
            bp.walk_container(bp.ATH11K_MAGIC[:10])

    def test_top_element_offsets_are_aligned(self):
        data = load("board2_ath11k.bin")
        _magic, _field, elements = bp.walk_container(data)
        for _id, body, length in elements:
            self.assertEqual(body, bp.align4(body - 8) + 8)
            self.assertEqual(bp.align4(length), length)


class TestElementWalk(unittest.TestCase):
    """The {le32 id, le32 len} sub-chain inside a top-level element."""

    def test_sub_chain_pairs_name_and_data(self):
        data = load("board2_ath11k.bin")
        _magic, _field, elements = bp.walk_container(data)
        subs = bp.walk_element(data, elements[0][1], elements[0][2])
        self.assertEqual([s[0] for s in subs], [bp.SUB_NAME, bp.SUB_DATA])
        name = data[subs[0][1]:subs[0][1] + subs[0][2]]
        self.assertTrue(name.startswith(b"bus=ahb,"))

    def test_pair_board_entries_returns_name_and_body(self):
        data = load("board2_ath11k.bin")
        _magic, _field, elements = bp.walk_container(data)
        subs = bp.walk_element(data, elements[0][1], elements[0][2])
        pairs = bp.pair_board_entries(data, subs)
        self.assertEqual(len(pairs), 1)
        self.assertIsNotNone(pairs[0][0])
        self.assertGreater(pairs[0][2], 0)

    def test_pair_reports_data_without_name(self):
        data = bytes(32)
        subs = [(bp.SUB_DATA, 8, 8)]
        pairs = bp.pair_board_entries(data, subs)
        self.assertEqual(len(pairs), 1)
        self.assertIsNone(pairs[0][0])

    def test_walk_element_raises_on_overrun(self):
        data = bytearray(64)
        struct.pack_into("<2I", data, 0, bp.SUB_NAME, 4000)
        with self.assertRaises(ValueError):
            bp.walk_element(bytes(data), 0, 64)


class TestElfUnwrap(unittest.TestCase):
    """The ELF32 wrapper around a board body."""

    def test_elf_payload_is_detected_and_unwrapped(self):
        result = bp.parse(load("board2_ath11k_elf.bin"))
        entry = result["board_entries"][0]
        self.assertTrue(entry["elf_wrapped"])
        self.assertGreater(entry["wrapper_bytes"], entry["body_bytes"])

    def test_elf_load_segment_finds_pt_load(self):
        data = load("board2_ath11k_elf.bin")
        _magic, _field, elements = bp.walk_container(data)
        subs = bp.walk_element(data, elements[0][1], elements[0][2])
        pairs = bp.pair_board_entries(data, subs)
        segment = bp.elf_load_segment(data, pairs[0][1], pairs[0][2])
        self.assertIsNotNone(segment)
        offset, length = segment
        self.assertGreater(offset, pairs[0][1])
        self.assertGreater(length, 0)

    def test_elf_phnum_is_index_ten_not_nine(self):
        data = load("board2_ath11k_elf.bin")
        _magic, _field, elements = bp.walk_container(data)
        subs = bp.walk_element(data, elements[0][1], elements[0][2])
        pairs = bp.pair_board_entries(data, subs)
        blob = data[pairs[0][1]:pairs[0][1] + pairs[0][2]]
        header = struct.unpack_from("<16sHHIIIIIHHHHHH", blob, 0)
        self.assertEqual(header[10], 1)
        self.assertEqual(header[9], 32)
        self.assertNotEqual(header[9], header[10])

    def test_elf_without_pt_load_returns_none(self):
        blob = bytearray(load("board2_ath11k_elf.bin"))
        _magic, _field, elements = bp.walk_container(bytes(blob))
        subs = bp.walk_element(bytes(blob), elements[0][1], elements[0][2])
        pairs = bp.pair_board_entries(bytes(blob), subs)
        patched = bytearray(blob)
        struct.pack_into("<I", patched, pairs[0][1] + 52, 0)
        self.assertIsNone(bp.elf_load_segment(bytes(patched), pairs[0][1], pairs[0][2]))

    def test_non_elf_returns_none(self):
        self.assertIsNone(bp.elf_load_segment(b"not an elf" + bytes(64), 0, 74))


class TestTagChain(unittest.TestCase):
    """The raw TLV tag chain, and the (0,0) sentinel trap."""

    def test_chain_walks_to_eof(self):
        body = make_fixture.simple_body(0x10, 6)
        tags, stop = bp.walk_tags(body)
        self.assertEqual(len(tags), 6)
        self.assertEqual(stop, "eof")
        self.assertEqual([t for t, _l, _o in tags], [1, 2, 3, 4, 5, 6])

    def test_chain_stops_at_sentinel(self):
        tags, stop = bp.walk_tags(load("body_sentinel.bin"))
        self.assertEqual(stop, "sentinel")
        self.assertEqual(len(tags), 3)

    def test_sentinel_prevents_phantom_tags(self):
        body = load("body_sentinel.bin")
        tags, _stop = bp.walk_tags(body)
        naive = 0
        offset = 0
        while offset + 4 <= len(body):
            _tag, length = struct.unpack_from("<2H", body, offset)
            naive += 1
            offset += 4 + length
        self.assertEqual(len(tags), 3)
        self.assertGreater(naive, 3)

    def test_chain_reports_overrun(self):
        tags, stop = bp.walk_tags(load("body_overrun.bin"))
        self.assertEqual(stop, "overrun")
        self.assertEqual(len(tags), 2)

    def test_zero_body_stops_immediately(self):
        tags, stop = bp.walk_tags(bytes(512))
        self.assertEqual(tags, [])
        self.assertEqual(stop, "sentinel")

    def test_tag_offsets_are_contiguous(self):
        body = make_fixture.simple_body(0x10, 6)
        tags, _stop = bp.walk_tags(body)
        expected = 0
        for _tag, length, offset in tags:
            self.assertEqual(offset, expected)
            expected += 4 + length

    def test_tag_lengths_are_not_padded(self):
        body = make_fixture.simple_body(0x10, 6)
        tags, _stop = bp.walk_tags(body)
        for _tag, length, _offset in tags:
            self.assertEqual(length % 4, 0)


class TestParse(unittest.TestCase):
    """End-to-end parse of each fixture."""

    def test_parse_counts(self):
        result = bp.parse(load("board2_ath11k.bin"))
        self.assertEqual(result["boards"], 2)
        self.assertEqual(result["regdbs"], 1)
        self.assertEqual(result["top_elements"], 3)
        self.assertEqual(result["magic"], "QCA-ATH11K-BOARD")
        self.assertEqual(result["magic_field"], 20)

    def test_parse_reports_names(self):
        result = bp.parse(load("board2_ath11k.bin"))
        names = [e["name"] for e in result["board_entries"]]
        self.assertIn("bus=ahb,qmi-chip-id=1,qmi-board-id=1", names)
