class AliasTests(unittest.TestCase):
    """Two virtual ranges onto one file range must not double-count."""

    def test_alias_fixture_has_two_sections(self):
        data = load("csffw_alias.bin")
        self.assertEqual(len(parser.sections(data)), 2)

    def test_alias_fixture_shares_one_range(self):
        data = load("csffw_alias.bin")
        rows = parser.sections(data)
        ranges = {(s["data_start"], s["data_end"]) for s in rows}
        self.assertEqual(len(ranges), 1)
        self.assertEqual(len(rows), 2)

    def test_alias_distinct_vas(self):
        data = load("csffw_alias.bin")
        rows = parser.sections(data)
        vas = {s["va_start"] for s in rows}
        self.assertEqual(len(vas), 2)

    def test_union_does_not_double_count(self):
        data = load("csffw_alias.bin")
        rows = parser.sections(data)
        naive = sum(s["data_end"] - s["data_start"] for s in rows)
        covered, _unclaimed = parser.union_coverage(data)
        self.assertEqual(covered, naive // 2)

    def test_union_equals_range_length(self):
        data = load("csffw_alias.bin")
        rows = parser.sections(data)
        expected = rows[0]["data_end"] - rows[0]["data_start"]
        covered, _unclaimed = parser.union_coverage(data)
        self.assertEqual(covered, expected)


class VectorTableTests(unittest.TestCase):
    """The vector table is located by va_start == 0, not by a fixed offset."""

    def test_vector_table_found(self):
        data = load("csffw_basic.bin")
        vector = parser.vector_table(data)
        self.assertIsNotNone(vector)

    def test_vector_table_values(self):
        data = load("csffw_basic.bin")
        sp, reset = parser.vector_table(data)
        self.assertEqual(sp, 0x02030000)
        self.assertEqual(reset, 0x00801FBD)

    def test_vector_sp_is_plausible_stack(self):
        data = load("csffw_basic.bin")
        sp, _reset = parser.vector_table(data)
        self.assertEqual(sp & 0xFFFF0000, 0x02030000)

    def test_vector_reset_is_thumb_code_window(self):
        data = load("csffw_basic.bin")
        _sp, reset = parser.vector_table(data)
        self.assertEqual(reset & 0xFFFF0000, 0x00800000)
        self.assertEqual(reset & 1, 1)

    def test_vector_absent_returns_none(self):
        data = load("csffw_trace.bin")
        self.assertIsNone(parser.vector_table(data))

    def test_vector_not_at_fixed_offset(self):
        data = load("csffw_basic.bin")
        vector = parser.vector_table(data)
        section = [s for s in parser.sections(data) if s["va_start"] == 0][0]
        self.assertNotEqual(section["data_start"], 0x1124)


class TraceBufferTests(unittest.TestCase):
    """Type-3 bodies: flags, five addresses, value, NUL-terminated ASCII name."""

    def test_trace_header_size(self):
        self.assertEqual(parser.TRACE_HEADER_SIZE, 28)

    def test_trace_names_decode(self):
        data = load("csffw_trace.bin")
        entries, _stop, _header = parser.walk_entries(data)
        traces = [parser.parse_trace_buffer(data, e) for e in entries if e["type"] == 3]
        names = [t["name"] for t in traces]
        self.assertEqual(names, ["firmware trace", "timeline"])

    def test_trace_names_are_printable(self):
        data = load("csffw_trace.bin")
        entries, _stop, _header = parser.walk_entries(data)
        for entry in entries:
            if entry["type"] == 3:
                trace = parser.parse_trace_buffer(data, entry)
                self.assertTrue(trace["name_printable"])

    def test_trace_has_five_addresses(self):
        data = load("csffw_trace.bin")
        entries, _stop, _header = parser.walk_entries(data)
        for entry in entries:
            if entry["type"] == 3:
                trace = parser.parse_trace_buffer(data, entry)
                self.assertEqual(len(trace["addresses"]), 5)

    def test_trace_flags_and_value(self):
        data = load("csffw_trace.bin")
        entries, _stop, _header = parser.walk_entries(data)
        traces = [parser.parse_trace_buffer(data, e) for e in entries if e["type"] == 3]
        self.assertEqual(traces[0]["flags"], 0x00000001)
        self.assertEqual(traces[0]["value"], 4)
        self.assertEqual(traces[1]["flags"], 0x00000000)
        self.assertEqual(traces[1]["value"], 1)

    def test_trace_name_stops_at_nul(self):
        data = load("csffw_trace.bin")
        entries, _stop, _header = parser.walk_entries(data)
        trace = parser.parse_trace_buffer(data, [e for e in entries if e["type"] == 3][0])
        self.assertNotIn("\x00", trace["name"])


