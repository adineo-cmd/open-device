#!/usr/bin/env python3
"""test_mali_csffw_parser.py — self-tests for the Mali CSF firmware parser.

CLEAN-ROOM STATEMENT
These tests assert the field layouts published in the Linux kernel driver
drivers/gpu/drm/panthor/panthor_fw.c (GPL-2.0, read 2026-11-28) against
fixtures generated by make_fixture.py. No proprietary payload, header or
string is used. The fixture files are .bin and are therefore gitignored, so
setUpModule regenerates them deterministically before any test runs.

The tests deliberately encode the traps that a naive parser falls into:

  * hdr_size is the descriptor table length, not the file length
  * entry advance is by the 8-bit size field, not an alignment
  * a zero-length section is legitimate and must not be rejected
  * sections alias one file range under two virtual ranges
  * the vector table is found by va_start == 0, not by a fixed offset
  * an entry size of zero is malformed, because there is no sentinel
"""

import os
import struct
import sys
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import make_fixture
import mali_csffw_parser as parser

FIXTURES = os.path.join(HERE, "fixtures")


def setUpModule():
    """Regenerate every fixture before the suite runs."""
    make_fixture.write_all()


def tearDownModule():
    """Leave the generated fixtures on disk for inspection."""
    return None


def load(name):
    """Read one generated fixture by file name."""
    with open(os.path.join(FIXTURES, name), "rb") as handle:
        return handle.read()


class HeaderTests(unittest.TestCase):
    """The 20-byte header and its magic gate."""

    def test_magic_constant(self):
        self.assertEqual(parser.CSF_FW_MAGIC, 0xC3F13A6E)

    def test_header_size_constant(self):
        self.assertEqual(parser.HEADER_SIZE, 20)

    def test_parse_header_fields(self):
        data = load("csffw_basic.bin")
        header = parser.parse_header(data)
        self.assertEqual(header["magic"], 0xC3F13A6E)
        self.assertEqual(header["major"], 0)
        self.assertEqual(header["minor"], 3)
        self.assertEqual(header["version_hash"], 0x01050000)
        self.assertEqual(header["pad1"], 0)
        self.assertEqual(header["pad2"], 0)

    def test_hdr_size_is_table_length_not_file_length(self):
        data = load("csffw_basic.bin")
        header = parser.parse_header(data)
        self.assertLess(header["hdr_size"], len(data))
        self.assertNotEqual(header["hdr_size"], len(data))

    def test_bad_magic_raises(self):
        data = load("csffw_bad_magic.bin")
        with self.assertRaises(ValueError):
            parser.parse_header(data)

    def test_short_buffer_raises(self):
        with self.assertRaises(ValueError):
            parser.parse_header(b"\x6e\x3a\xf1\xc3")

    def test_empty_buffer_raises(self):
        with self.assertRaises(ValueError):
            parser.parse_header(b"")


class EntryWalkTests(unittest.TestCase):
    """Bit extraction and the table walk."""

    def test_type_mask_is_low_byte(self):
        self.assertEqual(parser.entry_type(0x00000000), 0)
        self.assertEqual(parser.entry_type(0x000000FF), 0xFF)

    def test_size_field_is_second_byte(self):
        self.assertEqual(parser.entry_size(0x00002000), 0x20)
        self.assertEqual(parser.entry_size(0x0000FF00), 0xFF)

    def test_type_and_size_do_not_overlap(self):
        ehdr = 0x00000906
        self.assertEqual(parser.entry_type(ehdr), 6)
        self.assertEqual(parser.entry_size(ehdr), 9)

    def test_update_bit_is_30(self):
        self.assertTrue(parser.entry_update(1 << 30))
        self.assertFalse(parser.entry_update(1 << 29))
        self.assertFalse(parser.entry_update(0xFFFFFFFF & ~(1 << 30)))

    def test_optional_bit_is_31(self):
        self.assertTrue(parser.entry_optional(1 << 31))
        self.assertFalse(parser.entry_optional(1 << 30))

    def test_flags_do_not_leak_into_type_or_size(self):
        ehdr = (1 << 31) | (1 << 30) | (32 << 8) | 0
        self.assertEqual(parser.entry_type(ehdr), 0)
        self.assertEqual(parser.entry_size(ehdr), 32)

    def test_walk_stops_exactly_at_hdr_size(self):
        data = load("csffw_basic.bin")
        entries, stop, header = parser.walk_entries(data)
        self.assertEqual(stop, "table")
        last = entries[-1]
        self.assertEqual(last["body_end"], header["hdr_size"])

    def test_walk_entry_count(self):
        data = load("csffw_basic.bin")
        entries, _stop, _header = parser.walk_entries(data)
        self.assertEqual(len(entries), 11)

    def test_walk_advances_by_size_not_alignment(self):
        data = load("csffw_trace.bin")
        entries, stop, _header = parser.walk_entries(data)
        self.assertEqual(stop, "table")
        for entry in entries:
            self.assertEqual(entry["size"] % 4, 0)
            self.assertEqual(entry["body_end"] - entry["body_start"],
                             entry["size"] - 4)

    def test_zero_size_entry_is_malformed(self):
        data = load("csffw_zero_entry.bin")
        entries, stop, _header = parser.walk_entries(data)
        self.assertEqual(stop, "zero")
        self.assertEqual(entries, [])

    def test_short_table_reports_short(self):
        data = load("csffw_short.bin")
        entries, stop, _header = parser.walk_entries(data)
        self.assertEqual(stop, "short")
        self.assertEqual(entries, [])

    def test_type_histogram_of_basic_fixture(self):
        data = load("csffw_basic.bin")
        entries, _stop, _header = parser.walk_entries(data)
        counts = {}
        for entry in entries:
            counts[entry["type"]] = counts.get(entry["type"], 0) + 1
        self.assertEqual(counts[0], 3)
        self.assertEqual(counts[1], 1)
        self.assertEqual(counts[3], 1)
        self.assertEqual(counts[4], 1)
        self.assertEqual(counts[5], 1)
        self.assertEqual(counts[6], 1)
        self.assertEqual(counts[7], 1)
        self.assertEqual(counts[8], 1)
        self.assertEqual(counts[9], 1)

    def test_undocumented_types_are_not_named(self):
        for value in (5, 7, 8, 9):
            self.assertIsNone(parser.type_name(value))

    def test_documented_types_are_named(self):
        self.assertEqual(parser.type_name(0), "IFACE")
        self.assertEqual(parser.type_name(1), "CONFIG")
        self.assertEqual(parser.type_name(2), "FUTF_TEST")
        self.assertEqual(parser.type_name(3), "TRACE_BUFFER")
        self.assertEqual(parser.type_name(4), "TIMELINE_METADATA")
        self.assertEqual(parser.type_name(6), "BUILD_INFO_METADATA")


class SectionTests(unittest.TestCase):
    """Type-0 IFACE section bodies."""

    def test_section_body_is_five_words(self):
        self.assertEqual(parser.SECTION_HEADER_SIZE, 20)

    def test_parse_section_fields(self):
        data = load("csffw_basic.bin")
        entries, _stop, _header = parser.walk_entries(data)
        first = entries[0]
        section = parser.parse_section(data, first)
        self.assertEqual(section["flags"], 0x09)
        self.assertEqual(section["va_start"], 0x00400000)
        self.assertEqual(section["va_end"], 0x00410000)
        self.assertGreater(section["data_end"], section["data_start"])

    def test_section_entry_size_is_32(self):
        data = load("csffw_basic.bin")
        entries, _stop, _header = parser.walk_entries(data)
        for entry in entries:
            if entry["type"] == 0:
                self.assertEqual(entry["size"], 32)

    def test_section_list_count(self):
        data = load("csffw_basic.bin")
        self.assertEqual(len(parser.sections(data)), 3)

    def test_truncated_section_body_raises(self):
        data = load("csffw_basic.bin")
        entries, _stop, _header = parser.walk_entries(data)
        truncated = dict(entries[0])
        truncated["size"] = 8
        with self.assertRaises(ValueError):
            parser.parse_section(data, truncated)

    def test_section_name_is_empty_on_real_grammar(self):
        data = load("csffw_basic.bin")
        entries, _stop, _header = parser.walk_entries(data)
        for entry in entries:
            if entry["type"] == 0:
                self.assertEqual(parser.section_name(data, entry), "")

    def test_section_name_field_is_not_a_second_va_range(self):
        data = load("csffw_basic.bin")
        entries, _stop, _header = parser.walk_entries(data)
        entry = [e for e in entries if e["type"] == 0][0]
        start = entry["body_start"] + parser.SECTION_HEADER_SIZE
        tail = data[start:entry["body_end"]]
        self.assertEqual(tail[0], 0)

    def test_zero_length_section_is_accepted(self):
        data = load("csffw_zero_section.bin")
        found = [s for s in parser.sections(data) if s["data_start"] == s["data_end"]]
        self.assertEqual(len(found), 1)
        self.assertEqual(found[0]["data_start"], 0)
        self.assertEqual(found[0]["flags"], 0x2B)

    def test_zero_length_section_does_not_break_integrity(self):
        data = load("csffw_zero_section.bin")
        self.assertTrue(parser.integrity_ok(data))


