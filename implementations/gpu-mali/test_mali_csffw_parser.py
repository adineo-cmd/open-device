class ParseTests(unittest.TestCase):
    """The top-level parse() result."""

    def test_parse_reports_no_payload_bytes(self):
        data = load("csffw_basic.bin")
        result = parser.parse(data)
        for key, value in result.items():
            self.assertNotIsInstance(value, bytes, "key %s leaked bytes" % key)

    def test_parse_basic_shape(self):
        result = parser.parse(load("csffw_basic.bin"))
        self.assertEqual(result["bytes"], 4512)
        self.assertEqual(result["hdr_size"], 262)
        self.assertEqual(result["entries"], 11)
        self.assertEqual(result["stop"], "table")
        self.assertTrue(result["integrity_ok"])
        self.assertEqual(len(result["sections"]), 3)

    def test_parse_vector_present(self):
        result = parser.parse(load("csffw_basic.bin"))
        self.assertEqual(result["vector"], (0x02030000, 0x00801FBD))

    def test_parse_build_info(self):
        result = parser.parse(load("csffw_basic.bin"))
        self.assertTrue(result["build_info"].startswith("git_sha: "))

    def test_parse_trace_count(self):
        result = parser.parse(load("csffw_trace.bin"))
        self.assertEqual(len(result["traces"]), 2)

    def test_parse_zero_section_still_ok(self):
        result = parser.parse(load("csffw_zero_section.bin"))
        self.assertTrue(result["integrity_ok"])
        self.assertEqual(len(result["sections"]), 2)

    def test_format_report_contains_key_fields(self):
        result = parser.parse(load("csffw_basic.bin"))
        report = parser.format_report(result)
        self.assertIn("0xc3f13a6e", report)
        self.assertIn("descriptor table", report)
        self.assertIn("integrity ok", report)

    def test_format_report_names_undocumented_types(self):
        result = parser.parse(load("csffw_basic.bin"))
        report = parser.format_report(result)
        self.assertIn("type-5", report)
        self.assertIn("type-9", report)


